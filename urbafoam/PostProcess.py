import json

import numpy as np
from scipy.interpolate import NearestNDInterpolator, LinearNDInterpolator
from scipy.spatial import cKDTree

from .Paths import case_dir_name


def get_latest_time(times):
    time_numbers = [float(t) for t in times]
    max_index = time_numbers.index(max(time_numbers))
    return times[max_index]


VECTOR_FIELDS = {'U'}


def _field_sizes(fields, n_values):
    sizes = [3 if f in VECTOR_FIELDS else 1 for f in fields]
    if sum(sizes) != n_values:
        # older OpenFOAM versions write one file per value type, so all fields in a file have the same size
        if n_values % len(fields):
            raise ValueError(f"can't split {n_values} sampled values between the fields {fields}")
        sizes = [n_values // len(fields)] * len(fields)
    return sizes


def _find_field_file(sample_time_dir, sample_name, field):
    """Locate the raw set file holding `field` and return (path, column slice of the field).

    OpenFOAM's raw set writer names the file after the fields it holds, e.g. `<set>_k_p_U.xy`,
    with columns `x y z k p Ux Uy Uz` in the same order. (OpenFOAM v8 wrote one file per value
    type instead: `<set>_k_p.xy` and `<set>_U.xy`.)
    """
    prefix = f"{sample_name}_"
    for f in sorted(sample_time_dir.glob(f"{prefix}*.xy")):
        fields = f.stem[len(prefix):].split('_')
        if field not in fields:
            continue
        n_cols = np.loadtxt(f, max_rows=1, ndmin=1).shape[0]
        sizes = _field_sizes(fields, n_cols - 3)
        i = fields.index(field)
        start = 3 + sum(sizes[:i])
        return f, slice(start, start + sizes[i])
    raise FileNotFoundError(f"no sampled data for field '{field}' of '{sample_name}' in {sample_time_dir}")


def load_sample_points(case_dir, sample_name, field):
    """Return the sampled points (N x 3) and the values of `field` (N x components) at the latest time."""
    sample_dir = case_dir / "postProcessing" / "sampleDict"
    sample_times = [s.name for s in sample_dir.iterdir() if s.name.isdigit()] if sample_dir.is_dir() else []
    if len(sample_times) == 0:
        raise FileNotFoundError(f"no sample points found in {sample_dir}. Has the simulation run to completion?")
    max_time = get_latest_time(sample_times)
    sample_file, columns = _find_field_file(sample_dir / max_time, sample_name, field)
    sample_data = np.loadtxt(sample_file, ndmin=2)
    return sample_data[:, :3], sample_data[:, columns]


def orient_sample_date(case_dir, sample_name, field='U', Uref=None):
    """Load sampled data and rotate it back to the original model orientation.

    Returns rows of `x y z value` for scalar fields and
    `start_x start_y start_z end_x end_y end_z magnitude` for vector fields.
    """
    if not (case_dir / 'rotation_matrix.json').is_file():
        raise FileNotFoundError(f"could not find 'rotation_matrix.json' in {case_dir}, "
                                "was this case generated by Urbafoam?")

    with open(case_dir / 'rotation_matrix.json') as src:
        rotation_data = json.load(src)
    rotation_matrix = np.array(rotation_data['rot_matrix'])
    rotation_matrix = np.linalg.inv(rotation_matrix)  # rotating back to start_postion
    centerpoint = np.array(rotation_data['centerpoint'])

    start_points, data = load_sample_points(case_dir, sample_name, field)
    start_points = (start_points - centerpoint).dot(rotation_matrix) + centerpoint
    if data.shape[1] == 3:  # vector data
        if field == 'U' and (Uref is not None and Uref > 0):
            data = data / Uref
        vector_mag = np.linalg.norm(data, axis=1).reshape((-1, 1))
        # rotate the vector itself; it is a direction, so the centerpoint does not apply
        end_points = start_points + data.dot(rotation_matrix)
        return np.concatenate((start_points, end_points, vector_mag), axis=1)
    else:  # scalar data
        return np.concatenate((start_points, data), axis=1)


def write_oriented_data(case_dir, sample_name, field='U'):
    data = orient_sample_date(case_dir, sample_name, field)
    filename = f"{sample_name}_{field}.xyz"
    (case_dir / 'results').mkdir(exist_ok=True)
    np.savetxt(case_dir / 'results' / filename, data)


def find_sample_points_with_data(case_dir, sample_name, spacing, wind_directions, field='U', write=False):
    """Return the base sample points that have sampled data nearby in at least one wind direction.

    A base point is kept when a sampled point lies within a square of half-width 0.45 * spacing
    around it. Points are ordered by the first wind direction that has data for them, then by
    their order in sample_points.txt.
    """
    base_points = np.loadtxt(case_dir / "sample_points.txt", ndmin=2)[:, :2]
    # nextafter: the square is closed (points exactly on the edge count), the query bound is open
    half_width = np.nextafter(spacing * 0.45, np.inf)
    remaining = np.ones(len(base_points), dtype=bool)
    kept_index = []
    for w in wind_directions:
        case_data_points = orient_sample_date(case_dir / case_dir_name(w), sample_name, field)
        tree = cKDTree(case_data_points[:, :2])
        # p=inf: Chebyshev distance, i.e. an axis-aligned square around each base point
        distance, _ = tree.query(base_points, k=1, p=np.inf, distance_upper_bound=half_width)
        found = remaining & np.isfinite(distance)
        kept_index.extend(np.flatnonzero(found))
        remaining &= ~found
    kept_sample_points = base_points[np.array(kept_index, dtype=int)]
    if write:
        np.savetxt(case_dir / f"{sample_name}_sample_points.txt", kept_sample_points)
    return kept_sample_points


def normalize_oriented_data(base_points, case_dir, wind_directions, Uref, sample_name, field='U', speedup=True):
    interpZ_done = False
    if not speedup:
        Uref = None
    normalized_data = []
    for w in wind_directions:
        data = orient_sample_date(case_dir / case_dir_name(w), sample_name, field, Uref)
        # reduce data to just point and value
        points = data[:, :2]

        pointsZ = data[:, 2]
        if data.shape[1] == 7:  # vector field: use the magnitude
            data = data[:, 6]
        else:
            data = data[:, 3]
        if not interpZ_done:
            interpZ = NearestNDInterpolator(points, pointsZ)
            base_Z = interpZ(base_points)
            interpZ_done = True
        interp = LinearNDInterpolator(points, data)
        base_data = interp(base_points)

        # LinearND only works on points inside convex hull. Use this to set value on points
        # outside convex hull
        interp = NearestNDInterpolator(points, data)
        NN_base_data = interp(base_points)
        missing_data = np.isnan(base_data)
        base_data[missing_data] = NN_base_data[missing_data]

        normalized_data.append(base_data)
    base_points = np.hstack((base_points, base_Z.reshape((-1, 1))))
    return (base_points, normalized_data)
